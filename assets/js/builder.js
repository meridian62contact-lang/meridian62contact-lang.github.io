/* Meridian62 — Editors' tools: generates the files the site expects */
(function () {
  'use strict';
  var M = window.M62 || {}; var sectors = (M.sectors || []).slice().sort(function (a, b) { return a.number.localeCompare(b.number); });
  var repo = M.repo || 'USERNAME/REPOSITORY';
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  var q = function (s) { return JSON.stringify(String(s == null ? '' : s).trim()); }; /* safe YAML string */
  var BANNED = [/\bbuy\b/i, /\bsell\b/i, /\bcheap\b/i, /\bexpensive\b/i, /\bundervalued\b/i, /\bovervalued\b/i, /price target/i, /\bi(?:'d| would) invest/i, /\bbullish\b/i, /\bbearish\b/i, /\bshould (?:own|hold|buy|sell)\b/i, /\bgood (?:investment|buy)\b/i];

  /* tabs */
  $$('.tabs [data-tab]').forEach(function (b) {
    b.addEventListener('click', function () {
      $$('.tabs [data-tab]').forEach(function (x) { x.setAttribute('aria-selected', x === b ? 'true' : 'false'); });
      $$('[data-panel]').forEach(function (p) { p.classList.toggle('hidden', p.getAttribute('data-panel') !== b.getAttribute('data-tab')); });
    });
  });

  /* copy buttons */
  var toast = $('#toast');
  $$('[data-copy]').forEach(function (b) {
    b.addEventListener('click', function () {
      var text = $('#' + b.getAttribute('data-copy')).textContent;
      var done = function () { toast.classList.add('show'); setTimeout(function () { toast.classList.remove('show'); }, 1400); };
      if (navigator.clipboard) { navigator.clipboard.writeText(text).then(done); }
      else { var ta = document.createElement('textarea'); ta.value = text; document.body.appendChild(ta); ta.select(); document.execCommand('copy'); ta.remove(); done(); }
    });
  });

  function words(s) { return String(s || '').trim().split(/\s+/).filter(Boolean).length; }
  function isMonday(v) { if (!v) return false; var d = new Date(v + 'T12:00:00'); return d.getDay() === 1; }
  function check(list, ok, msg) { var li = document.createElement('li'); li.className = ok ? 'ok' : 'bad'; li.textContent = msg; list.appendChild(li); return ok; }
  function parseSources(text) {
    return String(text || '').split('\n').map(function (l) { return l.trim(); }).filter(Boolean).map(function (l) {
      var m = l.match(/^(.*?)\s*(https?:\/\/\S+)\s*$/); return m ? { name: m[1].replace(/[\s\-–—:]+$/, '').trim() || m[2], url: m[2] } : { name: l, url: '' };
    });
  }
  function bannedHits(text) { return BANNED.filter(function (r) { return r.test(text); }).length; }

  /* ---------------- WEEKLY NOTE ---------------- */
  var nf = $('#noteForm');
  if (nf) {
    var sel = $('#noteSector');
    sectors.forEach(function (s) { var o = document.createElement('option'); o.value = s.slug; o.textContent = s.number + ' · ' + s.name; sel.appendChild(o); });
    /* default week: next Monday */
    var d = new Date(); var add = (8 - d.getDay()) % 7 || 7; d.setDate(d.getDate() + add);
    $('#noteWeek').value = d.toISOString().slice(0, 10);

    function buildNote() {
      var f = nf.elements, list = $('#noteChecks'); list.innerHTML = '';
      var s = sectors.filter(function (x) { return x.slug === f.sector.value; })[0] || {};
      var week = f.week.value, headline = f.headline.value.trim();
      var body = [f.p1.value, f.p2.value, f.p3.value, f.p4.value].join(' ');
      var wc = words(body), srcs = parseSources(f.sources.value);
      var authors = f.authors.value.split(',').map(function (x) { return x.trim(); }).filter(Boolean);
      var equity = (f.company.value.trim() + (f.ticker.value.trim() ? ' · ' + f.ticker.value.trim().toUpperCase() : '')).trim();

      check(list, isMonday(week), week ? (isMonday(week) ? 'Week of is a Monday' : 'Week of must be a Monday (' + week + ' is not)') : 'Choose the Monday it publishes');
      check(list, !!f.company.value.trim(), 'Company named' + (f.company.value.trim() ? ': ' + equity : ''));
      check(list, headline && words(headline) <= 12, 'Headline ≤ 12 words (' + words(headline) + ')');
      check(list, wc >= 250 && wc <= 400, 'Word count 250–400 (' + wc + ')');
      check(list, srcs.length > 0 && srcs.every(function (x) { return x.url; }), srcs.length ? (srcs.every(function (x) { return x.url; }) ? srcs.length + ' source(s), all with links' : 'Every source needs a link starting with http') : 'At least one source');
      var hits = bannedHits(body + ' ' + headline);
      check(list, hits === 0, hits ? 'Advice language found — rephrase (buy / sell / cheap / expensive / undervalued / price target…)' : 'No advice language');
      check(list, !/\[\d\]/.test(body) || srcs.length > 0, 'Numbered references [1] [2] match the sources list');

      var fm = ['---',
        '# Weekly note — generated by the Editors\' tools. Do not rename the fields.',
        'sector: ' + (s.slug || ''),
        'week: ' + (week || 'YYYY-MM-DD'),
        'equity: ' + q(equity),
        'headline: ' + q(headline),
        'authors: [' + authors.map(q).join(', ') + ']',
        'published: true',
        '---', ''];
      var md = fm.concat([
        '### What happened', '', f.p1.value.trim(), '',
        '### What people are missing', '', f.p2.value.trim(), '',
        '### Why it matters', '', f.p3.value.trim(), '',
        '### What we are watching next', '', f.p4.value.trim(), ''
      ]);
      if (srcs.length) { md.push('## Sources', ''); srcs.forEach(function (x, i) { md.push((i + 1) + '. ' + (x.url ? '[' + x.name + '](' + x.url + ')' : x.name)); }); md.push(''); }
      $('#noteOut').textContent = md.join('\n');
      var fname = (week || 'YYYY-MM-DD') + '-' + (s.slug || 'sector') + '.md';
      $('#noteFilename').textContent = '_notes/' + fname;
      $('#noteGithub').href = 'https://github.com/' + repo + '/new/main/_notes?filename=' + encodeURIComponent(fname) + '&value=' + encodeURIComponent(md.join('\n'));

      /* glossary */
      var g = String(f.glossary.value || '').split('\n').map(function (l) { return l.trim(); }).filter(Boolean).map(function (l) {
        var m = l.match(/^(.+?)\s*[-–—:]\s+(.+)$/); return m ? { term: m[1].trim(), def: m[2].trim() } : { term: l, def: '' };
      });
      $('#glossaryWrap').classList.toggle('hidden', g.length === 0);
      $('#glossaryOut').textContent = g.map(function (x) { return '\n- term: ' + q(x.term) + '\n  definition: ' + q(x.def) + '\n  sector: ' + q(s.slug || ''); }).join('\n');
      $('#glossaryGithub').href = 'https://github.com/' + repo + '/edit/main/_data/glossary.yml';
    }
    nf.addEventListener('input', buildNote); nf.addEventListener('change', buildNote); buildNote();
  }

  /* ---------------- SECTOR SETUP ---------------- */
  var sf = $('#sectorForm');
  if (sf) {
    var ssel = $('#sectorSelect');
    sectors.forEach(function (s) { var o = document.createElement('option'); o.value = s.slug; o.textContent = s.number + ' · ' + s.name; ssel.appendChild(o); });
    var aRows = $('#analystRows'), eRows = $('#equityRows');
    function row(container, fields) {
      var div = document.createElement('div'); div.className = 'row-3'; div.style.marginBottom = '.6rem';
      fields.forEach(function (ph) { var i = document.createElement('input'); i.type = 'text'; i.placeholder = ph; i.setAttribute('data-f', ph); div.appendChild(i); });
      var rm = document.createElement('button'); rm.type = 'button'; rm.className = 'btn-mini'; rm.textContent = '×'; rm.addEventListener('click', function () { div.remove(); buildSector(); });
      div.appendChild(rm); container.appendChild(div); return div;
    }
    function fillSector() {
      var s = sectors.filter(function (x) { return x.slug === ssel.value; })[0]; if (!s) return;
      sf.elements.covers.value = s.covers || ''; sf.elements.image.value = s.image || ''; sf.elements.intro.value = '';
      aRows.innerHTML = ''; eRows.innerHTML = '';
      (s.analysts && s.analysts.length ? s.analysts : [{}, {}, {}]).forEach(function (a) { var r = row(aRows, ['Name', 'Degree', 'University']); var i = r.querySelectorAll('input'); i[0].value = a.name || ''; i[1].value = a.degree || ''; i[2].value = a.university || ''; });
      (s.equities && s.equities.length ? s.equities : [{}, {}, {}]).forEach(function (e) { var r = row(eRows, ['Company', 'Ticker', 'Coverage line (one sentence)']); var i = r.querySelectorAll('input'); i[0].value = e.company || ''; i[1].value = e.ticker || ''; i[2].value = e.watching || ''; });
      buildSector();
    }
    function buildSector() {
      var s = sectors.filter(function (x) { return x.slug === ssel.value; })[0] || {}; var list = $('#sectorChecks'); list.innerHTML = '';
      var an = $$('.row-3', aRows).map(function (r) { var i = r.querySelectorAll('input'); return { name: i[0].value, degree: i[1].value, university: i[2].value }; }).filter(function (a) { return a.name.trim(); });
      var eq = $$('.row-3', eRows).map(function (r) { var i = r.querySelectorAll('input'); return { company: i[0].value, ticker: i[1].value, watching: i[2].value }; }).filter(function (e) { return e.company.trim(); });
      check(list, an.length >= 1, an.length + ' analyst(s)');
      check(list, eq.length >= 3 && eq.length <= 5, eq.length + ' equities (needs 3–5)');
      check(list, eq.every(function (e) { return e.ticker.trim(); }), 'Every equity has a ticker');
      check(list, eq.every(function (e) { return e.watching.trim(); }), 'Every equity has a “watching” line');
      var out = ['---',
        '# ===== SECTOR ' + s.number + ' — ' + s.name + ' =====',
        '# Generated by the Editors\' tools. Keep the two-space indentation exactly as shown.',
        'number: ' + q(s.number), 'slug: ' + s.slug, 'name: ' + q(s.name),
        'covers: ' + q(sf.elements.covers.value), 'rota_group: ' + (s.group || 'A'), 'image: ' + q(sf.elements.image.value), '',
        'analysts:'];
      an.forEach(function (a) { out.push('  - name: ' + q(a.name), '    degree: ' + q(a.degree), '    university: ' + q(a.university)); });
      out.push('', 'equities:');
      eq.forEach(function (e) { out.push('  - company: ' + q(e.company), '    ticker: ' + q(e.ticker.toUpperCase()), '    watching: ' + q(e.watching)); });
      if (!eq.length) out.push('  []');
      out.push('---', '', sf.elements.intro.value.trim(), '');
      $('#sectorOut').textContent = out.join('\n');
      $('#sectorFilename').textContent = s.path || '';
      $('#sectorGithub').href = 'https://github.com/' + repo + '/edit/main/' + (s.path || '');
    }
    ssel.addEventListener('change', fillSector); sf.addEventListener('input', buildSector);
    $('#addAnalyst').addEventListener('click', function () { row(aRows, ['Name', 'Degree', 'University']); });
    $('#addEquity').addEventListener('click', function () { row(eRows, ['Company', 'Ticker', 'Coverage line (one sentence)']); });
    fillSector();
  }

  /* ---------------- QUARTERLY RECAP ---------------- */
  var rf = $('#recapForm');
  if (rf) {
    function buildRecap() {
      var f = rf.elements, list = $('#recapChecks'); list.innerHTML = '';
      var wc = words(f.body.value), srcs = parseSources(f.sources.value);
      var slug = String(f.quarter.value || 'quarter').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      check(list, !!f.title.value.trim(), 'Title present');
      check(list, wc >= 1500, 'Around 2,000 words (' + wc + ')');
      check(list, bannedHits(f.body.value) === 0, 'No advice language');
      check(list, srcs.length > 0, srcs.length + ' source(s)');
      var authors = f.authors.value.split(',').map(function (x) { return x.trim(); }).filter(Boolean);
      var out = ['---', 'title: ' + q(f.title.value), 'quarter: ' + q(f.quarter.value), 'slug: ' + slug, 'date: ' + (f.published.value || 'YYYY-MM-DD'), 'published: true',
        'lede: ' + q(f.lede.value), 'authors: [' + authors.map(q).join(', ') + ']', '---', '', f.body.value.trim(), ''];
      if (srcs.length) { out.push('## Sources', ''); srcs.forEach(function (x, i) { out.push((i + 1) + '. ' + (x.url ? '[' + x.name + '](' + x.url + ')' : x.name)); }); out.push(''); }
      $('#recapOut').textContent = out.join('\n');
      var fname = (f.published.value || 'YYYY-MM-DD') + '-' + slug + '.md';
      $('#recapFilename').textContent = '_recaps/' + fname;
      $('#recapGithub').href = 'https://github.com/' + repo + '/new/main/_recaps?filename=' + encodeURIComponent(fname) + '&value=' + encodeURIComponent(out.join('\n'));
    }
    rf.addEventListener('input', buildRecap); buildRecap();
  }
})();
